// Regenerates client/vendor/prosemirror.js from the pinned ProseMirror releases.
//
//   cd tools/vendor-prosemirror && npm ci && npm run build
//
// Why: the rich composer (client/composer/) edits the prompt with ProseMirror,
// but every ProseMirror module ships ES classes and the Hermes in React Native
// 0.81.5 rejects every form of `class`. Web and native load the same client
// bundle, so the editor has to compile on Hermes even though it only runs on
// web. Same recipe as tools/vendor-marked: bundle the packages into one ESM
// file, lower the classes with the class-only Babel plugins, minify with
// esbuild (target es2020), and refuse to write output that still has class
// syntax or a non-ASCII character.
//
// The types are copied next to it (client/vendor/prosemirror-types/) with
// their package specifiers rewritten, so the client type-checks without the
// packages installed at the repo root.
//
// The output is deterministic for a given lockfile: same inputs, same bytes.
import { createRequire } from "node:module";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const outDir = path.resolve(here, "../../client/vendor");
const typesDir = path.join(outDir, "prosemirror-types");

const babel = require("@babel/core");
const esbuild = require("esbuild");

/** The modules the client imports, in the order their types are re-exported. */
const MODULES = ["model", "transform", "state", "view", "keymap", "commands", "inputrules", "schema-list", "history"];
/** Packages the types import from, mapped to their copied file. */
const TYPE_FILES = Object.fromEntries([
  ...MODULES.map((name) => [`prosemirror-${name}`, name]),
  ["orderedmap", "orderedmap"],
]);
const LICENSED = [...MODULES.map((name) => `prosemirror-${name}`), "orderedmap", "rope-sequence", "w3c-keyname"];

const pkgDir = (name) => path.join(here, "node_modules", name);
const version = (name) => JSON.parse(readFileSync(path.join(pkgDir(name), "package.json"), "utf8")).version;

const entry = MODULES.map((name) => `export * from "prosemirror-${name}";`).join("\n");
const bundled = esbuild.buildSync({
  stdin: { contents: entry, resolveDir: here, loader: "js" },
  bundle: true,
  format: "esm",
  // Classes stay classes here; Babel lowers them below.
  target: "es2022",
  treeShaking: true,
  write: false,
  logLevel: "error",
}).outputFiles[0].text;

const plugin = (name) => require.resolve(`@babel/plugin-transform-${name}`);
const lowered = babel.transformSync(bundled, {
  babelrc: false,
  configFile: false,
  sourceType: "module",
  filename: "prosemirror.esm.js",
  comments: false,
  compact: true,
  sourceMaps: false,
  plugins: [
    plugin("class-static-block"),
    plugin("class-properties"),
    plugin("private-methods"),
    plugin("private-property-in-object"),
    plugin("classes"),
  ],
});
if (!lowered || typeof lowered.code !== "string") throw new Error("babel produced no output");

const minified = esbuild.transformSync(lowered.code, {
  loader: "js",
  format: "esm",
  target: "es2020",
  minify: true,
  legalComments: "none",
  // Escape every non-ASCII character: one raw character makes Hermes keep the
  // whole client source as two-byte text (scripts/check-hermes.mjs).
  charset: "ascii",
}).code;

// A leftover class or private name would fail on Hermes at load time, long
// after this script reported success, so the build re-parses its own output.
const leftovers = [];
babel.traverse(babel.parseSync(minified, { sourceType: "module", configFile: false, babelrc: false }), {
  enter(nodePath) {
    if (/^Class|PrivateName|StaticBlock/.test(nodePath.node.type)) leftovers.push(nodePath.node.type);
  },
});
if (leftovers.length > 0) throw new Error(`class syntax survived lowering: ${leftovers.slice(0, 5).join(", ")}`);
if (/[^\x00-\x7f]/.test(minified)) throw new Error("non-ASCII character survived minification");

const versions = MODULES.map((name) => `prosemirror-${name}@${version(`prosemirror-${name}`)}`).join(", ");
const banner = [
  "/**",
  ` * ProseMirror (${versions}), bundled, lowered for Hermes (no class syntax) and minified.`,
  " * GENERATED by tools/vendor-prosemirror/build.mjs; do not edit. License: ./prosemirror.LICENSE (MIT).",
  " * Upstream: https://prosemirror.net",
  " */",
  "// @ts-nocheck",
  "",
].join("\n");
writeFileSync(path.join(outDir, "prosemirror.js"), `${banner}${minified}`);

rmSync(typesDir, { recursive: true, force: true });
mkdirSync(typesDir, { recursive: true });
for (const [pkg, file] of Object.entries(TYPE_FILES)) {
  const source = readFileSync(path.join(pkgDir(pkg), "dist/index.d.ts"), "utf8");
  const rewritten = source.replace(/(from\s+['"])([^'"]+)(['"])/g, (match, open, specifier, close) => {
    const target = TYPE_FILES[specifier];
    if (!target) throw new Error(`${pkg} types import ${specifier}, which is not copied`);
    return `${open}./${target}${close}`;
  });
  writeFileSync(path.join(typesDir, `${file}.d.ts`), `// GENERATED by tools/vendor-prosemirror/build.mjs from ${pkg}@${version(pkg)}; do not edit.\n${rewritten}`);
}
writeFileSync(
  path.join(outDir, "prosemirror.d.ts"),
  [
    "// GENERATED by tools/vendor-prosemirror/build.mjs; do not edit.",
    ...MODULES.map((name) => `export * from "./prosemirror-types/${name}";`),
    "",
  ].join("\n"),
);

const licences = LICENSED.map((pkg) => `${pkg}@${version(pkg)}\n\n${readFileSync(path.join(pkgDir(pkg), "LICENSE"), "utf8").trim()}\n`);
writeFileSync(path.join(outDir, "prosemirror.LICENSE"), licences.join("\n----------------------------------------\n\n"));

console.log(
  `prosemirror: ${bundled.length} -> ${lowered.code.length} (lowered) -> ${minified.length} bytes (minified), babel ${babel.version}, esbuild ${esbuild.version}`,
);
